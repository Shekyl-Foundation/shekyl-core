def rows_of(claims: tuple[Claim, ...]) -> list[Row]:
    out: list[Row] = []
    for claim in claims:
        out.append(claim.row)
        if claim.falsifier is not None:
            out.append(claim.falsifier)
    return out


def check_claims(claims: tuple[Claim, ...]) -> None:
    """A held query with no row that flips it is a vacuous gate."""
    if not claims:
        sys.exit("run.py: no claims")
    seen: set[str] = set()
    for claim in claims:
        row = claim.row
        _check_row(row, seen)
        held = {name for name, verdict in row.expects if verdict is Verdict.HOLDS}
        falsifier = claim.falsifier
        if not held:
            if falsifier is not None:
                sys.exit(f"run.py: {row.name} is a stated non-property and names a falsifier")
            continue
        if falsifier is None:
            sys.exit(f"run.py: {row.name} holds {sorted(held)} and names no falsifier")
        _check_row(falsifier, seen)
        if falsifier.scenario is not row.scenario:
            sys.exit(f"run.py: {falsifier.name} is not the {row.scenario.value} scenario")
        if falsifier.edits == row.edits and falsifier.breaks == row.breaks:
            sys.exit(f"run.py: {falsifier.name} changes neither edits nor breaks")
        flipped = {name for name, verdict in falsifier.expects if verdict is Verdict.FAILS}
        missing = held - flipped
        if missing:
            sys.exit(f"run.py: {falsifier.name} does not flip {sorted(missing)}")


def _check_row(row: Row, seen: set[str]) -> None:
    if row.name in seen:
        sys.exit(f"run.py: duplicate variant {row.name}")
    seen.add(row.name)
    if not row.expects:
        sys.exit(f"run.py: {row.name} has no queries")
    names = [name for name, _ in row.expects]
    if len(names) != len(set(names)):
        sys.exit(f"run.py: {row.name} repeats a query")
    unknown = [name for name in names if name not in QUERIES]
    if unknown:
        sys.exit(f"run.py: {row.name} names unknown queries {unknown}")


def _labels(items: frozenset[enum.Enum]) -> str:
    return ", ".join(sorted(item.value for item in items)) or "none"


def render(row: Row) -> str:
    text = HEADER.format(
        name=row.name,
        scenario=row.scenario.value,
        edits=_labels(row.edits),
        breaks=_labels(row.breaks),
    )
    text += "\n"
    if Edit.REUSE_EPH in row.edits:
        text += "free ei_shared: scalar [private].\nfree eki_shared: kemsk [private].\n\n"
    text += Walk(Role.INITIATOR, row.edits, row.breaks).emit(row.scenario)
    text += "\n\n"
    text += Walk(Role.RESPONDER, row.edits, row.breaks).emit(row.scenario)
    text += "\n\n"
    text += "\n".join(QUERIES[name] for name, _ in row.expects)
    text += "\n\n"
    text += MAINS[row.scenario]
    if not text.endswith("\n"):
        text += "\n"
    return text


def check_variants(rows: list[Row]) -> str | None:
    if not VARIANTS.is_dir():
        return f"{VARIANTS.name}/ is missing; run --write-variants and commit it"
    want = {f"{row.name}.pv" for row in rows}
    have = {path.name for path in VARIANTS.glob("*.pv")}
    if have != want:
        extra = ", ".join(sorted(have - want)) or "-"
        missing = ", ".join(sorted(want - have)) or "-"
        return f"variant set drifted: extra {extra}; missing {missing}"
    for row in rows:
        path = VARIANTS / f"{row.name}.pv"
        if path.read_text(encoding="utf-8") != render(row):
            return f"{path.name} is stale; run --write-variants and commit it"
    return None


def write_variants(rows: list[Row]) -> None:
    VARIANTS.mkdir(parents=True, exist_ok=True)
    keep = {f"{row.name}.pv" for row in rows}
    for row in rows:
        (VARIANTS / f"{row.name}.pv").write_text(render(row), encoding="utf-8")
    for path in VARIANTS.glob("*.pv"):
        if path.name not in keep:
            path.unlink()


