Expects = tuple[tuple[str, Verdict], ...]


class Row:
    """One executed model: a scenario, the edits and breaks applied, and
    the verdict of each query, in the order ProVerif reports them."""

    def __init__(
        self,
        name: str,
        scenario: Scenario,
        edits: frozenset[Edit],
        breaks: frozenset[Break],
        expects: Expects,
    ):
        self.name = name
        self.scenario = scenario
        self.edits = edits
        self.breaks = breaks
        self.expects = expects


class Claim:
    """A property and, when it holds, the row that must flip it.
    A stated non-property has no falsifier: its own verdict is the failure."""

    def __init__(self, row: Row, falsifier: Row | None):
        self.row = row
        self.falsifier = falsifier


def _secrecy(reach: bool) -> Expects:
    rows: list[tuple[str, Verdict]] = [
        ("req_secret", Verdict.HOLDS),
        ("rep_secret", Verdict.HOLDS),
        ("key_secret_i2r", Verdict.HOLDS),
        ("key_secret_r2i", Verdict.HOLDS),
    ]
    if reach:
        rows.append(("reach_pair", Verdict.FAILS))
    return tuple(rows)


def _secrecy_fails() -> Expects:
    return (
        ("req_secret", Verdict.FAILS),
        ("rep_secret", Verdict.FAILS),
        ("key_secret_i2r", Verdict.FAILS),
        ("key_secret_r2i", Verdict.FAILS),
        ("reach_pair", Verdict.FAILS),
    )


def _later(holds: bool) -> Expects:
    verdict = Verdict.HOLDS if holds else Verdict.FAILS
    return (("req_secret_p1", verdict), ("rep_secret_p1", verdict))


