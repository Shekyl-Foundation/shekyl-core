# Rule 90: a commit message does not attribute the commit to an AI coding
# tool. The local commit-msg hook calls this on one message. CI calls it
# on every commit in a pull request. The hook is one clone's setup; this
# gate is what holds, because a commit that skipped the hook still fails
# here.
#
# Instance of 47-gate-subject-assertion.mdc. A range with no commits, or a
# missing message file, is exit 2. The self-test feeds a refused message
# and a clean one, and fails if the refused message is accepted.

from __future__ import annotations

import argparse
import re
import subprocess
import sys

# Tool names from rule 90, plus the addresses those tools put on a trailer.
TOOL = (
    r"cursor|cursoragent|claude|copilot|cody|chatgpt|codeium|tabnine"
)
COAUTHOR = re.compile(
    rf"(?im)^[ \t]*co-authored-by:.*\b(?:{TOOL})\b"
)
MADE_WITH = re.compile(r"(?im)^[ \t]*made[\s-]with\s*:")
GENERATED_BY = re.compile(r"(?i)\bgenerated by\b")
ASSISTED_BY = re.compile(r"(?i)\bassisted by\b")
# A subject-line mark that exists to say a tool wrote the commit.
ROBOT = re.compile(r"🤖")


def violations(message: str) -> list[str]:
    found = []
    if COAUTHOR.search(message):
        found.append("Co-authored-by names an AI coding tool")
    if MADE_WITH.search(message):
        found.append("Made-with trailer")
    if GENERATED_BY.search(message):
        found.append('"Generated by"')
    if ASSISTED_BY.search(message):
        found.append('"Assisted by"')
    subject = message.splitlines()[0] if message else ""
    if ROBOT.search(subject):
        found.append("robot mark in the subject")
    return found


def git_message(commit: str) -> str:
    proc = subprocess.run(
        ["git", "log", "-1", "--format=%B", commit],
        check=True,
        text=True,
        capture_output=True,
    )
    return proc.stdout


def commits_in(base: str, head: str) -> list[str]:
    proc = subprocess.run(
        ["git", "rev-list", "--reverse", f"{base}..{head}"],
        check=True,
        text=True,
        capture_output=True,
    )
    return [line for line in proc.stdout.splitlines() if line]


def check_range(base: str, head: str) -> int:
    if not base or not head:
        print("commit messages: base and head are required", file=sys.stderr)
        return 2
    try:
        commits = commits_in(base, head)
    except subprocess.CalledProcessError as err:
        sys.stderr.write(err.stderr or "")
        print("commit messages: could not list the range", file=sys.stderr)
        return 2
    if not commits:
        print(
            f"commit messages: no commits in {base}..{head}",
            file=sys.stderr,
        )
        return 2
    bad = 0
    for commit in commits:
        message = git_message(commit)
        found = violations(message)
        if not found:
            continue
        bad += 1
        subject = message.splitlines()[0] if message else ""
        print(
            f"commit messages: {commit[:12]} {subject}: {'; '.join(found)}",
            file=sys.stderr,
        )
    if bad:
        print(f"commit messages: {bad} commit(s) attribute an AI tool", file=sys.stderr)
        return 1
    print(f"commit messages: {len(commits)} commit(s) clean")
    return 0


def check_file(path: str) -> int:
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            message = handle.read()
    except OSError as err:
        print(f"commit messages: cannot read {path}: {err}", file=sys.stderr)
        return 2
    found = violations(message)
    if found:
        print(
            "commit messages: " + "; ".join(found),
            file=sys.stderr,
        )
        return 1
    return 0


def selftest() -> int:
    clean = "sim: record a measurement\n\nThe June pins reproduce.\n"
    human = clean + "Co-authored-by: Ada Lovelace <ada@example.com>\n"
    refused = [
        clean + "Co-authored-by: Cursor <cursoragent@cursor.com>\n",
        clean + "Co-authored-by: Claude <noreply@anthropic.com>\n",
        clean + "Made with: Cursor\n",
        clean + "Generated by a coding tool.\n",
        clean + "Assisted by the editor.\n",
        "🤖 sim: record a measurement\n",
    ]
    if violations(clean) or violations(human):
        print("commit messages: selftest accepted a clean message as refused", file=sys.stderr)
        return 1
    for message in refused:
        if not violations(message):
            print("commit messages: selftest missed a refused message", file=sys.stderr)
            print(message, file=sys.stderr)
            return 1
    print("commit messages: selftest passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base")
    parser.add_argument("--head")
    parser.add_argument("--message-file")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()
    modes = [args.selftest, bool(args.message_file), bool(args.base or args.head)]
    if sum(bool(m) for m in modes) != 1:
        print(
            "commit messages: pass exactly one of --selftest, --message-file, or --base/--head",
            file=sys.stderr,
        )
        return 2
    if args.selftest:
        return selftest()
    if args.message_file:
        return check_file(args.message_file)
    return check_range(args.base or "", args.head or "")


if __name__ == "__main__":
    sys.exit(main())
