# The struct-layout limb of the FFI signature gate
# (scripts/ci/check_ffi_signatures.sh). A struct crossing the boundary is
# defined twice: #[repr(C)] in Rust and by hand in src/shekyl/shekyl_ffi.h.
# C++ reading a struct whose fields moved does not fail. It reads support
# flags out of a height. This script compares each pair the gate's LAYOUTS
# list names:
#
#   1. Member NAMES, in order, both ways. A member only one side has fails
#      here by name, including one sitting in the other side's padding,
#      which every size and offset would still agree with.
#   2. It writes the static_asserts ffi_layout_gate.cpp compiles: size,
#      alignment, and each member's offset and type, the Rust struct
#      (cbindgen-generated into namespace rust_layout) against the
#      hand-written one. Offsets are keyed by name, so two members of one
#      width swapped on one side fail even though the size agrees.
#
# Usage: ffi_layout_gate.py HEADER GENERATED OUT Rust=c [Rust=c ...]

import re
import sys


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def body_of(text, name):
    """The member text of struct `name`'s definition, or None."""
    match = re.search(r"\bstruct\s+" + re.escape(name) + r"\s*\{", text)
    if match is None:
        return None
    depth, start = 1, match.end()
    for at in range(start, len(text)):
        if text[at] == "{":
            depth += 1
        elif text[at] == "}":
            depth -= 1
            if depth == 0:
                return text[start:at]
    return None


def members(body, where):
    """Member names in declaration order."""
    names = []
    for decl in body.split(";"):
        decl = " ".join(decl.split())
        if not decl or decl.startswith("static_assert"):
            continue
        # A default initializer is not part of the layout.
        decl = re.split(r"\s*[={]", decl, maxsplit=1)[0]
        if "," in decl:
            sys.exit(f"error: {where}: '{decl}' declares several members; "
                     "write one per declaration")
        # A pointer-to-array member: `const uint8_t (*name)[N]`.
        pointer = re.search(r"\(\s*\*\s*([A-Za-z_]\w*)\s*\)", decl)
        if pointer:
            names.append(pointer.group(1))
            continue
        decl = re.sub(r"(\s*\[[^\]]*\])+$", "", decl)
        name = re.search(r"([A-Za-z_]\w*)$", decl)
        if name is None or "(" in decl:
            sys.exit(f"error: {where}: cannot read a member name from '{decl}'")
        names.append(name.group(1))
    return names


def main():
    header_path, generated_path, out_path, *pairs = sys.argv[1:]
    header = strip_comments(open(header_path, encoding="utf-8").read())
    generated = strip_comments(open(generated_path, encoding="utf-8").read())
    if not pairs:
        sys.exit("error: no layout pairs given")

    twins, asserts = [], []
    for pair in pairs:
        rust, c = pair.split("=")
        rust_body = body_of(generated, rust)
        if rust_body is None:
            sys.exit(f"error: {rust} is missing from the generated header: "
                     "the struct moved or is no longer #[repr(C)]")
        c_body = body_of(header, c)
        if c_body is None:
            sys.exit(f"error: struct {c} (twin of {rust}) has no definition "
                     f"in {header_path}")
        rust_members = members(rust_body, rust)
        c_members = members(c_body, c)
        if not rust_members:
            sys.exit(f"error: {rust} generated with no members")
        if rust_members != c_members:
            sys.exit(f"error: struct {c} does not have the members of {rust}, "
                     f"in order:\n  Rust: {' '.join(rust_members)}\n"
                     f"  C++:  {' '.join(c_members)}")
        twins.append(f"template <> struct norm<rust_layout::{rust}> "
                     f"{{ using type = ::{c}; }};")
        r, h = f"rust_layout::{rust}", f"::{c}"
        asserts.append(f"static_assert(sizeof({r}) == sizeof({h}), "
                       f'"{c}: size");')
        asserts.append(f"static_assert(alignof({r}) == alignof({h}), "
                       f'"{c}: alignment");')
        for m in rust_members:
            asserts.append(f"static_assert(offsetof({r}, {m}) == "
                           f'offsetof({h}, {m}), "{c}::{m}: offset");')
            asserts.append(f"static_assert(ffi_layout_gate::same<decltype({r}::{m}), "
                           f'decltype({h}::{m})>, "{c}::{m}: type");')

    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// Generated by scripts/ci/ffi_layout_gate.py.\n")
        out.write("namespace ffi_layout_gate {\n")
        out.write("\n".join(twins) + "\n}  // namespace ffi_layout_gate\n\n")
        out.write("\n".join(asserts) + "\n")
    print(len(pairs))


if __name__ == "__main__":
    main()
