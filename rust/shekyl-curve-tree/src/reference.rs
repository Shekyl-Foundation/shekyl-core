//! Reference-block selection and proof validity-horizon arithmetic
//! (`docs/design/CURVE_TREE_CLIENT.md` §5).
//!
//! A membership proof is anchored to a *reference block* — a recent
//! block whose header-committed curve-tree root the proof is built
//! against. Consensus admits a spend into the block connecting at height
//! `C` iff the reference block's age *from that connecting height*
//! (`C − reference_height`) is in `[MIN_AGE, MAX_AGE]` (CEN-I11,
//! `shekyl_chain_rules::admissible_references`). Seen from a wallet whose
//! tip is `tip`, the next block connects at `tip + 1`.
//!
//! Two clocks live here, and each function says which it reads:
//!
//! - **Connecting age** (`tip + 1 − reference_height`), what consensus
//!   measures: [`proof_submittable`] and [`proof_expired`].
//! - **Tip age** (`tip − reference_height`, [`reference_block_age`]), the
//!   wallet's own clock: [`select_reference_height`] ([`REF_ANCHOR_AGE`],
//!   privacy-canonical — it is the on-wire age every honest wallet shows)
//!   and [`should_reanchor`] ([`REBUILD_AT`], wallet hygiene).
//!
//! This module owns the wallet-side arithmetic for:
//!
//! 1. **Selecting** the canonical reference height for a fresh proof
//!    (`tip − REF_ANCHOR_AGE`, §5.1). Every honest wallet uses the same
//!    offset — the age is observable on every tx, so a per-wallet offset
//!    would fingerprint the wallet (`00-mission.mdc` priority 2; same
//!    uniformity logic as dust `K_DUST`).
//! 2. **Bounding** how long a built proof stays submittable (the
//!    validity horizon, §5.2) and deciding when to proactively
//!    **re-anchor** an in-flight proof before it expires mid-flight.
//!
//! ## Why arithmetic, not a `ReferenceBlock` constructor
//!
//! [`crate::CurveTreeClient`] does not store block-header roots — the
//! caller supplies the consensus [`crate::ReferenceBlock`] (height +
//! header root) that [`crate::CurveTreeClient::assemble_path`] verifies
//! the reconstructed root against. So reference-block *selection* is
//! height arithmetic the caller drives against its own chain view; this
//! module exposes that arithmetic as total, side-effect-free functions
//! over heights. Binding a height to a consensus root remains the
//! caller's responsibility (the caller-supplies-root integrity model,
//! §3.5). No secrets, no I/O, no chain access here.

